-- Initial PRET web application schema.
-- All application objects are explicitly placed in the public schema.
-- Run this against a database you have already created and configured.

CREATE TABLE public.app_users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identity_provider varchar(64) NOT NULL,
    identity_subject varchar(255) NOT NULL,
    username varchar(255) NOT NULL,
    role varchar(16) NOT NULL DEFAULT 'operator'
        CHECK (role IN ('operator', 'admin')),
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    last_login_at timestamptz,
    CONSTRAINT app_users_provider_subject_key
        UNIQUE (identity_provider, identity_subject)
);

CREATE TABLE public.devices (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_ip inet NOT NULL
        CHECK (
            masklen(target_ip) =
            CASE family(target_ip) WHEN 4 THEN 32 ELSE 128 END
        ),
    port integer NOT NULL DEFAULT 9100 CHECK (port BETWEEN 1 AND 65535),
    hostname text,
    model text,
    firmware text,
    mac_address varchar(17),
    location text,
    contact text,
    protocol_hint varchar(32),
    status varchar(16) NOT NULL DEFAULT 'unknown'
        CHECK (status IN ('online', 'offline', 'unknown')),
    first_seen_at timestamptz NOT NULL DEFAULT now(),
    last_seen_at timestamptz,
    added_by_user_id bigint
        REFERENCES public.app_users(id) ON DELETE SET NULL,
    source varchar(32) NOT NULL DEFAULT 'manual'
        CHECK (source IN ('manual', 'snmp_discovery', 'mdns_discovery')),
    CONSTRAINT devices_target_ip_port_key UNIQUE (target_ip, port)
);

CREATE TABLE public.device_services (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id bigint NOT NULL
        REFERENCES public.devices(id) ON DELETE CASCADE,
    port integer NOT NULL CHECK (port BETWEEN 1 AND 65535),
    protocol_name varchar(64) NOT NULL,
    state varchar(16) NOT NULL
        CHECK (state IN ('open', 'closed', 'filtered')),
    detected_at timestamptz NOT NULL DEFAULT now(),
    detection_method varchar(64) NOT NULL,
    CONSTRAINT device_services_device_port_protocol_key
        UNIQUE (device_id, port, protocol_name)
);

CREATE TABLE public.authorized_networks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    network cidr NOT NULL UNIQUE,
    is_enabled boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by_user_id bigint
        REFERENCES public.app_users(id) ON DELETE SET NULL
);

CREATE TABLE public.jobs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id bigint REFERENCES public.devices(id) ON DELETE SET NULL,
    adapter_id varchar(64) NOT NULL,
    operation_id varchar(128) NOT NULL,
    status varchar(16) NOT NULL DEFAULT 'queued'
        CHECK (
            status IN (
                'queued', 'running', 'succeeded', 'failed',
                'cancelled', 'timeout'
            )
        ),
    requested_by_user_id bigint
        REFERENCES public.app_users(id) ON DELETE SET NULL,
    requested_at timestamptz NOT NULL DEFAULT now(),
    started_at timestamptz,
    finished_at timestamptz,
    is_state_changing boolean NOT NULL DEFAULT false,
    confirmation_token text,
    params_json jsonb NOT NULL DEFAULT '{}'::jsonb
        CHECK (jsonb_typeof(params_json) = 'object'),
    CHECK (
        (is_state_changing AND confirmation_token IS NOT NULL)
        OR (NOT is_state_changing AND confirmation_token IS NULL)
    )
);

CREATE TABLE public.results (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id bigint NOT NULL REFERENCES public.jobs(id) ON DELETE CASCADE,
    device_id bigint REFERENCES public.devices(id) ON DELETE SET NULL,
    adapter_id varchar(64) NOT NULL,
    operation_id varchar(128) NOT NULL,
    recorded_at timestamptz NOT NULL DEFAULT now(),
    status varchar(16) NOT NULL
        CHECK (status IN ('ok', 'error', 'timeout', 'unsupported')),
    severity varchar(16)
        CHECK (
            severity IS NULL OR severity IN (
                'info', 'low', 'medium', 'high', 'critical'
            )
        ),
    summary text NOT NULL,
    evidence_json jsonb NOT NULL DEFAULT '{}'::jsonb
        CHECK (
            jsonb_typeof(evidence_json) IN ('object', 'array', 'string',
                                            'number', 'boolean', 'null')
        ),
    remediation text,
    error_detail text,
    adapter_version varchar(64),
    CHECK (
        pg_column_size(evidence_json) <= 16384
    )
);

CREATE TABLE public.audit_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    action varchar(128) NOT NULL,
    target_device_id bigint
        REFERENCES public.devices(id) ON DELETE SET NULL,
    job_id bigint REFERENCES public.jobs(id) ON DELETE SET NULL,
    recorded_at timestamptz NOT NULL DEFAULT now(),
    source_ip inet,
    outcome varchar(16) NOT NULL CHECK (outcome IN ('success', 'failure')),
    detail jsonb NOT NULL DEFAULT '{}'::jsonb
        CHECK (jsonb_typeof(detail) = 'object')
);

CREATE TABLE public.credentials (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id bigint NOT NULL
        REFERENCES public.devices(id) ON DELETE CASCADE,
    kind varchar(32) NOT NULL
        CHECK (kind IN ('snmp_v2c', 'snmp_v3', 'http_basic')),
    encrypted_blob bytea NOT NULL,
    created_by_user_id bigint
        REFERENCES public.app_users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.settings (
    key varchar(128) PRIMARY KEY,
    value_json jsonb NOT NULL,
    updated_by_user_id bigint
        REFERENCES public.app_users(id) ON DELETE SET NULL,
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX devices_target_ip_idx
    ON public.devices (target_ip);
CREATE INDEX devices_status_idx
    ON public.devices (status);
CREATE INDEX device_services_device_id_idx
    ON public.device_services (device_id);
CREATE INDEX authorized_networks_enabled_idx
    ON public.authorized_networks (is_enabled);
CREATE INDEX jobs_status_requested_at_idx
    ON public.jobs (status, requested_at);
CREATE INDEX jobs_device_id_requested_at_idx
    ON public.jobs (device_id, requested_at);
CREATE INDEX results_device_id_recorded_at_idx
    ON public.results (device_id, recorded_at);
CREATE INDEX results_job_id_idx
    ON public.results (job_id);
CREATE INDEX audit_log_recorded_at_idx
    ON public.audit_log (recorded_at);
CREATE INDEX credentials_device_id_idx
    ON public.credentials (device_id);

CREATE FUNCTION public.purge_expired_history()
RETURNS TABLE (deleted_jobs bigint, deleted_audit_entries bigint)
LANGUAGE plpgsql
AS $function$
BEGIN
    DELETE FROM public.jobs
    WHERE status IN ('succeeded', 'failed', 'cancelled', 'timeout')
      AND finished_at < now() - interval '90 days';
    GET DIAGNOSTICS deleted_jobs = ROW_COUNT;

    DELETE FROM public.audit_log
    WHERE recorded_at < now() - interval '90 days';
    GET DIAGNOSTICS deleted_audit_entries = ROW_COUNT;

    RETURN NEXT;
END;
$function$;

REVOKE ALL ON FUNCTION public.purge_expired_history() FROM PUBLIC;

COMMENT ON TABLE public.credentials IS
    'encrypted_blob must contain application-encrypted credentials; never store plaintext secrets.';
COMMENT ON TABLE public.audit_log IS
    'Audit events should be append-only through the application.';
COMMENT ON FUNCTION public.purge_expired_history() IS
    'Deletes completed jobs and audit entries older than 90 days; grant execution only to a trusted scheduler role.';
